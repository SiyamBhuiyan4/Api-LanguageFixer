import Cocoa
import ApplicationServices
import Carbon.HIToolbox

public final class TextEngine {
    public static let shared = TextEngine()

    private let pasteboard = NSPasteboard.general

    // Virtual key codes
    private static let kVK_C: CGKeyCode = 0x08 // 'c'
    private static let kVK_V: CGKeyCode = 0x09 // 'v'

    // Transient pasteboard types to prevent clipboard history pollution
    private static let transientTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    ]

    private init() {}

    // MARK: - Snapshot Model

    public struct ClipboardSnapshot {
        public let items: [[NSPasteboard.PasteboardType: Data]]
        public let changeCount: Int
    }

    public func snapshotClipboard() -> ClipboardSnapshot {
        var items: [[NSPasteboard.PasteboardType: Data]] = []
        if let pbItems = pasteboard.pasteboardItems {
            for item in pbItems {
                var dict: [NSPasteboard.PasteboardType: Data] = [:]
                for type in item.types {
                    if let data = item.data(forType: type) {
                        dict[type] = data
                    }
                }
                if !dict.isEmpty {
                    items.append(dict)
                }
            }
        }
        return ClipboardSnapshot(items: items, changeCount: pasteboard.changeCount)
    }

    public func restoreClipboard(from snapshot: ClipboardSnapshot, expectedChangeCount: Int? = nil) {
        if let expected = expectedChangeCount, pasteboard.changeCount != expected {
            // User copied something new during the operation; do not overwrite
            return
        }

        pasteboard.clearContents()
        guard !snapshot.items.isEmpty else { return }

        var pbItems: [NSPasteboardItem] = []
        for dict in snapshot.items {
            let item = NSPasteboardItem()
            for (type, data) in dict {
                item.setData(data, forType: type)
            }
            pbItems.append(item)
        }
        pasteboard.writeObjects(pbItems)
    }

    // MARK: - Target Inspection

    public enum Editability: Equatable {
        case editable
        case readOnly
        case unknown  // The app doesn't expose this (common in browsers and Electron apps)
    }

    /// The app the user is working in. A slow AI reply must not paste into a different app.
    public var frontmostProcessID: pid_t? {
        NSWorkspace.shared.frontmostApplication?.processIdentifier
    }

    public func focusedTargetEditability() -> Editability {
        guard let element = focusedElement() else { return .unknown }

        var settable = DarwinBoolean(false)
        for attribute in [kAXSelectedTextAttribute, kAXValueAttribute] {
            if AXUIElementIsAttributeSettable(element, attribute as CFString, &settable) == .success, settable.boolValue {
                return .editable
            }
        }

        var roleRef: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXRoleAttribute as CFString, &roleRef) == .success,
              let role = roleRef as? String else {
            return .unknown
        }

        // A text control that refuses edits, or plain page text. A web area stays
        // "unknown" because editors such as Google Docs report that role too.
        let readOnlyRoles: Set<String> = [
            "AXTextField", "AXTextArea", "AXComboBox", "AXSearchField",
            "AXStaticText", "AXLink", "AXHeading", "AXImage", "AXButton"
        ]
        return readOnlyRoles.contains(role) ? .readOnly : .unknown
    }

    private func focusedElement() -> AXUIElement? {
        let systemWide = AXUIElementCreateSystemWide()
        var focusedRef: CFTypeRef?
        guard AXUIElementCopyAttributeValue(systemWide, kAXFocusedUIElementAttribute as CFString, &focusedRef) == .success,
              let focused = focusedRef, CFGetTypeID(focused) == AXUIElementGetTypeID() else {
            return nil
        }
        return (focused as! AXUIElement)
    }

    // MARK: - Text Capture

    /// Waits for the hotkey's Command and Shift to be released, so the synthetic
    /// Cmd+C can't reach the app as Cmd+Shift+C (DevTools in Chrome).
    private func waitForModifierRelease() async {
        let deadline = Date().addingTimeInterval(0.7)
        while Date() < deadline {
            let flags = CGEventSource.flagsState(.combinedSessionState)
            if !flags.contains(.maskShift) && !flags.contains(.maskCommand) { return }
            try? await Task.sleep(nanoseconds: 15_000_000)
        }
    }

    public func captureSelectedText() async -> String? {
        // Guard against password fields
        if IsSecureEventInputEnabled() {
            return nil
        }

        await waitForModifierRelease()

        // Try Strategy 1: Pasteboard via simulated Cmd+C
        let snapshot = snapshotClipboard()
        let initialChangeCount = pasteboard.changeCount

        let copySynthesized = synthesizeKey(keyCode: Self.kVK_C, flags: .maskCommand)
        var capturedText: String? = nil

        if copySynthesized {
            // Poll changeCount; browsers and Electron apps can take a few hundred ms to copy
            let start = DispatchTime.now().uptimeNanoseconds
            let timeoutNano: UInt64 = 600_000_000 // 600ms
            let pollNano: UInt64 = 10_000_000     // 10ms

            while DispatchTime.now().uptimeNanoseconds - start < timeoutNano {
                try? await Task.sleep(nanoseconds: pollNano)
                if pasteboard.changeCount != initialChangeCount {
                    capturedText = pasteboard.string(forType: .string)
                    break
                }
            }
        }

        // Restore original clipboard, but only if the copy actually changed it
        if pasteboard.changeCount != initialChangeCount {
            restoreClipboard(from: snapshot)
        }

        if let text = capturedText, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return text
        }

        // Strategy 2: Fallback to Accessibility API
        if let axText = captureViaAccessibility(), !axText.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return axText
        }

        return nil
    }

    private func captureViaAccessibility() -> String? {
        guard let element = focusedElement() else { return nil }

        // 1. Try kAXSelectedTextAttribute
        var selectedTextRef: CFTypeRef?
        if AXUIElementCopyAttributeValue(element, kAXSelectedTextAttribute as CFString, &selectedTextRef) == .success,
           let text = selectedTextRef as? String, !text.isEmpty {
            return text
        }

        // 2. Try kAXSelectedTextRangeAttribute + kAXValueAttribute
        var rangeRef: CFTypeRef?
        var valueRef: CFTypeRef?
        if AXUIElementCopyAttributeValue(element, kAXSelectedTextRangeAttribute as CFString, &rangeRef) == .success,
           AXUIElementCopyAttributeValue(element, kAXValueAttribute as CFString, &valueRef) == .success,
           let fullText = valueRef as? String,
           let axRange = rangeRef as! AXValue? {
            var cfRange = CFRange()
            if AXValueGetType(axRange) == .cfRange && AXValueGetValue(axRange, .cfRange, &cfRange) {
                if cfRange.length > 0 && cfRange.location >= 0 {
                    let nsString = fullText as NSString
                    if cfRange.location + cfRange.length <= nsString.length {
                        return nsString.substring(with: NSRange(location: cfRange.location, length: cfRange.length))
                    }
                }
            }
        }

        return nil
    }

    // MARK: - Text Replacement

    public func replaceSelectedText(with text: String, restoringClipboardAfter delay: TimeInterval = 0.8) async {
        guard !text.isEmpty else { return }
        await waitForModifierRelease()

        // Snapshot existing clipboard
        let snapshot = snapshotClipboard()

        // Write replacement text with transient privacy flags
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for t in Self.transientTypes {
            item.setString("1", forType: t)
        }
        pasteboard.writeObjects([item])

        let aiPasteChangeCount = pasteboard.changeCount

        // Synthesize Cmd+V
        _ = synthesizeKey(keyCode: Self.kVK_V, flags: .maskCommand)

        // Restore the clipboard only after slower apps have read it; too soon and they paste the old contents
        try? await Task.sleep(nanoseconds: UInt64(delay * 1_000_000_000))
        restoreClipboard(from: snapshot, expectedChangeCount: aiPasteChangeCount)
    }

    /// Puts text on the clipboard at the user's request (the Copy button).
    public func copyToClipboard(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }

    // MARK: - Key Event Synthesis

    private func synthesizeKey(keyCode: CGKeyCode, flags: CGEventFlags) -> Bool {
        let source = CGEventSource(stateID: .combinedSessionState)

        guard let keyDown = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: true),
              let keyUp = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: false) else {
            return false
        }

        keyDown.flags = flags
        keyUp.flags = flags

        keyDown.post(tap: .cghidEventTap)
        usleep(10_000) // 10ms hold
        keyUp.post(tap: .cghidEventTap)

        return true
    }
}
